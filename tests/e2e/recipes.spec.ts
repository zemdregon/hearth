test('imported fixture is reviewed before saving, and sends only selected recipe text', async ({ page }) => {
  const fixture = { ...createDemo(), demo: false };
  const imported: Recipe = { title: 'Imported test recipe', description: 'Fixture extraction, not a live AI call.', servings: 2, prepMinutes: 5, cookMinutes: 15, ingredients: [{ name: 'rice', quantity: .5, unit: 'cup' }], steps: ['Cook the rice.'], tags: [], favorite: false };
  let saves = 0;
  await page.route('**/api/bootstrap', route => route.fulfill({ json: fixture }));
  await page.route('**/api/recipes/import', async route => {
    expect(route.request().postDataJSON()).toEqual({ mode: 'text', value: 'Rice, ½ cup. Cook for 15 minutes.' });
    await route.fulfill({ json: { recipe: imported, warnings: ['Fixture warning: check serving size.'] } });
  });
  await page.route('**/api/records', async route => {
    const input = route.request().postDataJSON();
    saves += 1;
    const record = { id: 'test-import', kind: 'recipe', data: input.data, ownerId: fixture.user.id, version: 1, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() } as FamilyRecord<'recipe'>;
    fixture.records.push(record);
    await route.fulfill({ status: 201, json: record });
  });
  await page.goto('/#recipes');
  await page.getByRole('button', { name: 'Import recipe', exact: true }).click();
  await page.getByRole('button', { name: 'Paste text', exact: true }).click();
  await page.getByLabel('Recipe text', { exact: true }).fill('Rice, ½ cup. Cook for 15 minutes.');
  await page.getByRole('button', { name: 'Create a recipe draft' }).click();
  const review = page.getByRole('dialog', { name: 'Review your imported recipe' });
  await expect(review).toBeVisible();
  expect(saves).toBe(0);
  await expect(review).toContainText('Fixture warning: check serving size.');
  await review.getByLabel('Recipe name').fill('Reviewed rice recipe');
  await review.getByRole('button', { name: 'Save recipe' }).click();
  await expect(review).toHaveCount(0);
  expect(saves).toBe(1);
  await expect(page.getByRole('button', { name: 'View Reviewed rice recipe' })).toBeVisible();
});

