test('recipe editor blocks closing and edits during a pending save, then recovers from failure', async ({ page }) => {
  const fixture = { ...createDemo(), demo: false };
  let writes = 0;
  let releaseSave: () => void = () => undefined;
  await page.route('**/api/bootstrap', route => route.fulfill({ json: fixture }));
  await page.route('**/api/records', async route => {
    const attempt = ++writes;
    const input = route.request().postDataJSON();
    await new Promise<void>(resolve => { releaseSave = resolve; });
    if (attempt === 1) return route.fulfill({ status: 500, json: { error: 'Fixture save failed. Please try again.' } });
    const record = { id: 'delayed-recipe', kind: 'recipe', data: input.data, ownerId: fixture.user.id, version: 1, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() } as FamilyRecord<'recipe'>;
    fixture.records.push(record);
    return route.fulfill({ status: 201, json: record });
  });
  await page.goto('/#recipes');
  await page.getByRole('button', { name: 'Add recipe', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Something good to keep' });
  await dialog.getByLabel('Recipe name').fill('Slow original recipe');
  await dialog.getByLabel('Ingredient 1 name').fill('flour');
  await dialog.getByLabel('Step 1', { exact: true }).fill('Mix gently.');
  await dialog.getByRole('button', { name: 'Save recipe' }).click();
  await expect.poll(() => writes).toBe(1);
  await expect(dialog.getByLabel('Recipe name')).toBeDisabled();
  await expect(dialog.getByLabel('Ingredient 1 name')).toBeDisabled();
  await expect(dialog.getByRole('button', { name: 'Add ingredient' })).toBeDisabled();
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await expect(dialog).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(dialog).toBeVisible();
  await page.mouse.click(2, 2);
  await expect(dialog).toBeVisible();
  expect(writes).toBe(1);
  releaseSave();
  await expect(dialog.getByRole('alert')).toContainText('Fixture save failed.');
  await expect(dialog.getByLabel('Recipe name')).toBeEnabled();
  await expect(dialog.getByLabel('Recipe name')).toHaveValue('Slow original recipe');
  await dialog.getByLabel('Recipe name').fill('Retried slow recipe');
  await dialog.getByRole('button', { name: 'Save recipe' }).click();
  await expect.poll(() => writes).toBe(2);
  await page.keyboard.press('Escape');
  await expect(dialog).toBeVisible();
  releaseSave();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'View Retried slow recipe' })).toBeVisible();
});
